"""Summarize the Jev spend ledger (cache/ledger.jsonl) into docs/SPEND.md.  python -m englishnet.spend"""
import json
import statistics
from collections import defaultdict
from datetime import datetime, timezone

from .config import DOCS, JEV_BUDGET_USD
from .jev import LEDGER


def main():
    rows = [json.loads(l) for l in LEDGER.open() if l.strip()] if LEDGER.exists() else []
    by = defaultdict(lambda: {"calls": 0, "tokens": 0, "usd": 0.0, "ms": [], "first": None})
    for r in rows:
        b = by[r["purpose"] or "(none)"]
        b["calls"] += 1; b["tokens"] += r["tokens"]; b["usd"] += r["usd"]; b["ms"].append(r["ms"])
        b["first"] = b["first"] or r["t"]
    tot = sum(b["usd"] for b in by.values())
    lines = ["# Jev spend", "",
             f"Budget for the whole build: {JEV_BUDGET_USD:.2f} USD (enforced in `englishnet/jev.py`). "
             f"Price: 0.042 USD per million input tokens; output tokens are free. Every answer is cached in "
             f"`cache/jev.sqlite`, so reruns cost nothing. Generated by `python -m englishnet.spend` from "
             f"`cache/ledger.jsonl` (one line per real API call).", "",
             f"**Total: {len(rows):,} calls, {sum(b['tokens'] for b in by.values()):,} tokens, {tot:.4f} USD.**", "",
             "| Step | First call (UTC) | Calls | Tokens | USD | Median latency (ms) |", "|---|---|---|---|---|---|"]
    for k, b in sorted(by.items(), key=lambda kv: kv[1]["first"]):
        lines.append(f"| {k} | {datetime.fromtimestamp(b["first"], timezone.utc).strftime('%Y-%m-%d %H:%M')} | {b['calls']:,} | "
                     f"{b['tokens']:,} | {b['usd']:.4f} | {statistics.median(b['ms']):.0f} |")
    lines += ["", "The prototype experiment (Oct 19, before this repo) spent a further 0.094 USD; it is not in this ledger.", ""]
    DOCS.mkdir(exist_ok=True)
    (DOCS / "SPEND.md").write_text("\n".join(lines))
    print("\n".join(lines[6:]))


if __name__ == "__main__":
    main()
